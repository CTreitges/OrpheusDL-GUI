"""hires/audio_convert.py against real ffmpeg, checked with ffprobe.

Every source file is generated by ffmpeg itself (a sine tone), tagged with
mutagen and given a cover, so the tests need no fixture files and no network.
They skip only where ffmpeg/ffprobe or mutagen are missing (CI installs both
on Linux; the Windows run of the DJ upgrade has them locally).
"""

import json
import os
import shutil
import subprocess
import sys
import threading
import time

import pytest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

mutagen = pytest.importorskip("mutagen")
FFMPEG = shutil.which("ffmpeg")
FFPROBE = shutil.which("ffprobe")
pytestmark = pytest.mark.skipif(not (FFMPEG and FFPROBE), reason="ffmpeg/ffprobe not installed")

from hires import audio_convert as ac  # noqa: E402
from hires.audio_tags import read_tags  # noqa: E402

#: A 1x1 PNG, enough for "the cover survived".
PNG = bytes.fromhex(
    "89504e470d0a1a0a0000000d4948445200000001000000010806000000"
    "1f15c4890000000d49444154789c6360000002000154a24f5d0000000049454e44ae426082"
)


def make_tone(path, *, rate=96000, bits=24, seconds=2.0, channels=2, codec=None):
    """A sine tone in the format the extension says, written by ffmpeg."""
    args = [FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
            "-i", f"sine=frequency=440:sample_rate={rate}:duration={seconds}"]
    if channels > 1:
        args += ["-ac", str(channels)]
    ext = os.path.splitext(path)[1]
    if codec:
        args += ["-c:a", codec]
    elif ext == ".flac":
        args += ["-c:a", "flac"] + (["-sample_fmt", "s32", "-bits_per_raw_sample", "24"]
                                    if bits == 24 else ["-sample_fmt", "s16"])
    elif ext == ".wav":
        args += ["-c:a", f"pcm_s{bits}le"]
    elif ext == ".m4a":
        args += ["-c:a", "aac", "-b:a", "256k"]
    args.append(path)
    subprocess.run(args, check=True)
    return path


def tag_flac(path):
    from mutagen.flac import FLAC, Picture

    audio = FLAC(path)
    audio["title"] = "Tone"
    audio["artist"] = "Sine Wave"
    audio["album"] = "Test Crate"
    audio["isrc"] = "DEX123456789"
    audio["bpm"] = "124"
    picture = Picture()
    picture.data, picture.mime, picture.type = PNG, "image/png", 3
    audio.add_picture(picture)
    audio.save()


def ffprobe(path):
    out = subprocess.run(
        [FFPROBE, "-v", "error", "-select_streams", "a:0", "-show_entries",
         "stream=codec_name,sample_rate,bits_per_sample,bits_per_raw_sample,channels:format=duration",
         "-of", "json", path],
        check=True, capture_output=True, text=True,
    ).stdout
    data = json.loads(out)
    stream = data["streams"][0]
    bits = int(stream.get("bits_per_raw_sample") or 0) or int(stream.get("bits_per_sample") or 0)
    return {
        "codec": stream["codec_name"],
        "rate": int(stream["sample_rate"]),
        "bits": bits,
        "duration": float(data["format"]["duration"]),
    }


@pytest.fixture
def flac24(tmp_path):
    path = make_tone(str(tmp_path / "tone.flac"), rate=96000, bits=24)
    tag_flac(path)
    return path


class TestLosslessConversions:
    def test_audio_convert_flac_to_wav_keeps_rate_depth_length(self, flac24):
        before = ffprobe(flac24)
        result = ac.convert_file(flac24, "wav", ffmpeg=FFMPEG)
        assert result.status == "converted", result.reason
        after = ffprobe(result.output)
        assert after["codec"] == "pcm_s24le"
        assert (after["rate"], after["bits"]) == (96000, 24)
        assert abs(after["duration"] - before["duration"]) <= 0.010
        assert not os.path.exists(flac24) and result.removed_original

    def test_audio_convert_flac_to_wav_carries_tags_and_cover(self, flac24):
        result = ac.convert_file(flac24, "wav", ffmpeg=FFMPEG)
        from mutagen.wave import WAVE

        tags = WAVE(result.output).tags
        assert str(tags["TIT2"]) == "Tone" and str(tags["TPE1"]) == "Sine Wave"
        assert str(tags["TSRC"]) == "DEX123456789" and str(tags["TBPM"]) == "124"
        assert tags.getall("APIC")[0].data == PNG

    def test_audio_convert_flac_to_aiff_keeps_everything(self, flac24):
        before = ffprobe(flac24)
        result = ac.convert_file(flac24, "aiff", ffmpeg=FFMPEG, keep_original=True)
        assert result.status == "converted", result.reason
        after = ffprobe(result.output)
        assert after["codec"] == "pcm_s24be"
        assert (after["rate"], after["bits"]) == (96000, 24)
        assert abs(after["duration"] - before["duration"]) <= 0.010
        values, covers = read_tags(result.output)
        assert values["title"] == ["Tone"] and values["album"] == ["Test Crate"]
        assert covers and covers[0].data == PNG
        assert os.path.exists(flac24), "Keep original must keep the source"

    def test_audio_convert_wav_to_flac_16_bit(self, tmp_path):
        source = make_tone(str(tmp_path / "cd.wav"), rate=44100, bits=16)
        from mutagen.wave import WAVE
        from mutagen.id3 import TIT2, APIC

        wav = WAVE(source)
        wav.add_tags()
        wav.tags.add(TIT2(encoding=3, text=["CD Tone"]))
        wav.tags.add(APIC(encoding=3, mime="image/png", type=3, desc="", data=PNG))
        wav.save()
        before = ffprobe(source)
        result = ac.convert_file(source, "flac", ffmpeg=FFMPEG)
        assert result.status == "converted", result.reason
        after = ffprobe(result.output)
        assert (after["codec"], after["rate"], after["bits"]) == ("flac", 44100, 16)
        assert abs(after["duration"] - before["duration"]) <= 0.010
        values, covers = read_tags(result.output)
        assert values["title"] == ["CD Tone"] and covers[0].data == PNG

    def test_audio_convert_never_raises_the_bit_depth(self, tmp_path):
        source = make_tone(str(tmp_path / "cd.flac"), rate=44100, bits=16)
        result = ac.convert_file(source, "aiff", ffmpeg=FFMPEG)
        after = ffprobe(result.output)
        assert (after["codec"], after["rate"], after["bits"]) == ("pcm_s16be", 44100, 16)


class TestLossySource:
    def test_audio_convert_lossy_source_is_flagged_and_16_bit(self, tmp_path):
        source = make_tone(str(tmp_path / "sc.m4a"), rate=44100)
        result = ac.convert_file(source, "wav", ffmpeg=FFMPEG)
        assert result.status == "converted", result.reason
        assert result.lossy_source and result.reason == ac.LOSSY_WARNING
        after = ffprobe(result.output)
        assert (after["codec"], after["rate"]) == ("pcm_s16le", 44100)


class TestOriginalIsSafe:
    def test_audio_convert_missing_ffmpeg_keeps_the_original(self, flac24, tmp_path):
        result = ac.convert_file(flac24, "wav", ffmpeg=str(tmp_path / "no-ffmpeg.exe"))
        assert result.status == "failed"
        assert os.path.exists(flac24)
        assert not os.path.exists(ac.output_path_for(flac24, "wav"))
        assert not os.path.exists(ac.output_path_for(flac24, "wav") + ".part")

    def test_audio_convert_bad_result_keeps_the_original(self, flac24, monkeypatch):
        monkeypatch.setattr(ac, "_verify", lambda *a: "length changed (2.00 s → 1.00 s)")
        result = ac.convert_file(flac24, "wav", ffmpeg=FFMPEG)
        assert result.status == "failed" and "length changed" in result.reason
        assert sorted(os.listdir(os.path.dirname(flac24))) == ["tone.flac"]

    def test_audio_convert_tag_failure_keeps_the_original(self, flac24, monkeypatch):
        def boom(*_a):
            raise OSError("disk full")

        monkeypatch.setattr(ac, "write_tags", boom)
        result = ac.convert_file(flac24, "aiff", ffmpeg=FFMPEG)
        assert result.status == "failed" and "tags" in result.reason
        assert sorted(os.listdir(os.path.dirname(flac24))) == ["tone.flac"]

    def test_audio_convert_corrupt_file_fails_without_damage(self, tmp_path):
        broken = tmp_path / "broken.flac"
        broken.write_bytes(b"not audio at all" * 10)
        result = ac.convert_file(str(broken), "wav", ffmpeg=FFMPEG)
        assert result.status == "failed"
        assert broken.read_bytes() == b"not audio at all" * 10

    def test_audio_convert_cancel_keeps_the_original(self, flac24):
        cancel = threading.Event()
        cancel.set()
        result = ac.convert_file(flac24, "wav", ffmpeg=FFMPEG, cancel=cancel)
        assert result.status == "cancelled"
        assert sorted(os.listdir(os.path.dirname(flac24))) == ["tone.flac"]

    def test_audio_convert_existing_target_is_never_overwritten(self, flac24):
        target = ac.output_path_for(flac24, "wav")
        with open(target, "wb") as handle:
            handle.write(b"mine")
        result = ac.convert_file(flac24, "wav", ffmpeg=FFMPEG)
        assert result.status == "skipped" and result.reason == "target file exists"
        assert open(target, "rb").read() == b"mine" and os.path.exists(flac24)


class TestSkips:
    def test_audio_convert_same_format_is_skipped(self, flac24):
        assert ac.convert_file(flac24, "flac", ffmpeg=FFMPEG).status == "skipped"

    def test_audio_convert_float_wav_is_not_squeezed_into_flac(self, tmp_path):
        source = make_tone(str(tmp_path / "float.wav"), rate=48000, codec="pcm_f32le")
        assert ac.probe(source).is_float
        result = ac.convert_file(source, "flac", ffmpeg=FFMPEG)
        assert result.status == "skipped" and os.path.exists(source)

    def test_audio_convert_spatial_audio_is_left_alone(self, tmp_path):
        source = make_tone(str(tmp_path / "atmos.flac"), rate=48000, bits=24, channels=6)
        result = ac.convert_file(source, "wav", ffmpeg=FFMPEG)
        assert result.status == "skipped" and "spatial" in result.reason


class TestFoldersAndPlaylists:
    def test_audio_convert_folder_walks_subfolders(self, tmp_path):
        for name in ("a/one.flac", "a/b/two.flac", "three.m4a"):
            os.makedirs(os.path.dirname(str(tmp_path / name)), exist_ok=True)
            make_tone(str(tmp_path / name), rate=44100, bits=16, seconds=0.5)
        (tmp_path / "cover.jpg").write_bytes(b"jpg")
        summary = ac.convert_folder(str(tmp_path), "aiff", ffmpeg=FFMPEG)
        assert (summary.found, summary.converted, summary.failed) == (3, 3, 0)
        assert sorted(os.path.basename(p) for p in ac.find_audio(str(tmp_path))) == [
            "one.aiff", "three.aiff", "two.aiff"]

    def test_audio_convert_find_audio_since_skips_older_files(self, tmp_path):
        old = make_tone(str(tmp_path / "old.flac"), seconds=0.2)
        if not hasattr(os.stat(old), "st_birthtime") and sys.platform != "win32":
            os.utime(old, (time.time() - 3600, time.time() - 3600))
        time.sleep(0.05)
        since = time.time()
        time.sleep(0.05)
        new = make_tone(str(tmp_path / "new.flac"), seconds=0.2)
        assert ac.find_audio(str(tmp_path), since=since) == [new]

    def test_audio_convert_playlists_point_at_the_new_files(self, tmp_path):
        folder = tmp_path / "My Set"
        folder.mkdir()
        playlist = folder / "My Set.m3u"
        playlist.write_text("#EXTM3U\n#EXTINF:2,Tone\ntone.flac\nother.mp3\n", encoding="utf-8")
        renamed = {str(folder / "tone.flac"): str(folder / "tone.aiff")}
        assert ac.rewrite_playlists([str(playlist)], renamed) == 1
        assert playlist.read_text(encoding="utf-8") == "#EXTM3U\n#EXTINF:2,Tone\ntone.aiff\nother.mp3\n"


class TestLabels:
    def test_audio_convert_describe_labels(self):
        assert ac.describe(ac.AudioInfo("flac", 96000, 24)) == "FLAC 24-bit/96 kHz"
        assert ac.describe(ac.AudioInfo("flac", 44100, 16)) == "FLAC 16-bit/44.1 kHz"
        assert ac.describe(ac.AudioInfo("aac", 44100, None, 256000)) == "AAC 256 kbit/s"
        assert ac.describe(ac.AudioInfo("opus", 48000, None, 0)) == "OPUS"
        assert ac.describe(None) == ""

    def test_audio_convert_summarize_mixed_files(self):
        assert ac.summarize(["FLAC 16-bit/44.1 kHz"] * 3) == "FLAC 16-bit/44.1 kHz"
        assert ac.summarize(["A", "B", "A", ""]) == "A ×2 · B ×1"
        assert ac.summarize([]) == ""
